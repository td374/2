"""Stage 3.2 -- build the **training-volume-matched** cross/single datasets.

The scientific question
-----------------------
``audit/STAGE3_EVIDENCE_CHAIN.md`` (and the user's framing) asks:

    After controlling the TEST OBJECT and the TRAINING SAMPLE SIZE, does
    cross-condition data carry degradation information beyond what the target
    condition already provides?

The 5-fold matched pilot (``scripts/19_make_matched_folds.py``) fixes the test
object -- inside a fold the in-condition and cross arms share a byte-identical
test bearing -- but it does **not** fix the training volume. ``scripts/22``
measured cross/single ``n_train`` ratios spanning **0.07x-18.35x**, and the sign
flips with the target condition (target 1 always MORE source data, target 3
always LESS). So a raw ``R_cross`` conflates

    different condition  (the effect we want)
  + different training volume (a confound)

What this script does
---------------------
For every ``(fold, target)`` it takes the four arms that enter that unit's
comparison --

    single_cond{t}          (in-condition)
    cross_{a}_to_{t}        (single source)
    cross_{b}_to_{t}        (single source)
    cross_{a+b}_to_{t}      (multi source)

-- and caps **all four** to the same ``K = min(n_train over the four arms)``
windows. Both arms of every paired contrast therefore train on *exactly* the
same number of windows, and the single factor left is *which condition the
training data came from*.

How the cap is applied
----------------------
* **Per-bearing proportional, evenly-spaced in time.** The ``K`` slots are
  allocated across the training bearings by largest-remainder in proportion to
  each bearing's window count, then ``linspace`` picks evenly spaced windows
  inside each bearing. This is exactly "raise the effective stride", so it keeps
  every bearing's life-stage coverage and its relative weight.
* **The scaler is refit** on the capped training split (``ChannelScaler``), i.e.
  the arm is reprocessed end-to-end on the data it actually sees.
* **mRMR indices are left untouched.** They are fitted on *snapshot-level*
  training-bearing features (``build._select_features``), which do not depend on
  the window count; "which bearings" is precisely the treatment, so keeping them
  is the correct behaviour, not a leak.
* **val / test are byte-identical to the pilot folds.** The only change relative
  to ``artifacts/data_fold{k}`` is the training-split size, which makes
  ``vm_fold{k}`` vs ``matched_fold{k}`` a clean one-factor contrast on volume.

Outputs
-------
    artifacts/data_vm_fold{k}/{single_cond*,cross_*}.npz (+ .json sidecar)
    configs/matched_folds_vm/fold{k}.yaml
    artifacts/reports/volume_matched_design.{json,md}

Pure data transformation -- trains nothing.

Usage
-----
    python scripts/28_make_volume_matched.py
    python scripts/28_make_volume_matched.py --folds 1 --out-root artifacts/data_vm_fold1
"""

from __future__ import annotations

import argparse
import json
import pathlib
import re
import shutil
import sys

import numpy as np

REPO = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from rulbench.data.scaling import ChannelScaler  # noqa: E402

CONFIG_TEMPLATE = """\
# AUTO-GENERATED by scripts/28_make_volume_matched.py -- do not edit by hand.
# Stage 3.2 volume-matched fold {k}: every arm of every (fold, target) unit is
# capped to K = min(n_train) windows, so in-condition and cross-condition arms
# train on EXACTLY the same number of windows. Only the source condition varies.

data:
  label:
    strategy: linear
    healthy_ratio: 0.8        # ignored by the linear strategy; kept for reference

paths:
  data_dir: {data_dir}
  report_dir: {report_dir}

splits:
  # kept for provenance only -- the npz are pre-built, so prepare is skipped
  single:
    train: {train}
    val: [{v}]
    test: [{k}]
  cross:
    source_train: {train}
    source_val: [{v}]
    target_test: [{k}]

uda:
  enabled: true

model:
  mmd_feature: flatten

experiments:
  single:
    models: {models}
  cross:
    models: {models}

report:
  headline_metric: rmse
"""


def _target_of(stem: str):
    """Map a dataset stem to its target condition, or None if not a unit arm."""
    m = re.match(r"^single_cond(\d)$", stem)
    if m:
        return m.group(1)
    m = re.match(r"^cross_.+_to_(\d)$", stem)
    if m:
        return m.group(1)
    return None


def _allocate(counts, K):
    """Largest-remainder allocation of ``K`` slots across groups sized ``counts``."""
    total = int(sum(counts))
    if K > total:
        raise ValueError(f"K={K} exceeds available windows {total}")
    quota = [K * c / total for c in counts]
    alloc = [int(np.floor(q)) for q in quota]
    rem = K - sum(alloc)
    if rem > 0:
        order = sorted(range(len(counts)), key=lambda i: quota[i] - alloc[i], reverse=True)
        for i in order[:rem]:
            alloc[i] += 1
    # never exceed a group's size, then repair any deficit by relative fill
    alloc = [min(a, c) for a, c in zip(alloc, counts)]
    deficit = K - sum(alloc)
    while deficit > 0:
        cand = [i for i in range(len(counts)) if alloc[i] < counts[i]]
        if not cand:
            break
        cand.sort(key=lambda i: alloc[i] / max(counts[i], 1))
        for i in cand:
            if deficit == 0:
                break
            alloc[i] += 1
            deficit -= 1
    return alloc


def _subsample_index(bearing_ids, conditions, K):
    """Return the (sorted) window indices to keep, spread across bearings and time."""
    groups: dict = {}
    for i, (c, b) in enumerate(zip(conditions.tolist(), bearing_ids.tolist())):
        groups.setdefault((int(c), int(b)), []).append(i)
    keys = list(groups.keys())
    counts = [len(groups[k]) for k in keys]
    alloc = _allocate(counts, K)

    picked = []
    for key, n_i in zip(keys, alloc):
        idxs = groups[key]
        if n_i >= len(idxs):
            picked.extend(idxs)
        else:
            pos = np.linspace(0, len(idxs) - 1, n_i)
            picked.extend(idxs[int(round(p))] for p in pos)
    return np.array(sorted(picked), dtype=np.int64)


def _cap_train(arrays: dict, K: int):
    """Subsample the train split to ``K`` windows and refit the scaler."""
    idx = _subsample_index(arrays["train/bearing_id"], arrays["train/condition"], K)
    for field in ("X", "ratio", "lifetime", "bearing_id", "condition", "window_end"):
        key = f"train/{field}"
        if key in arrays:
            arrays[key] = arrays[key][idx]
    scaler = ChannelScaler().fit(arrays["train/X"])
    arrays["scaler_mean"] = scaler.mean_
    arrays["scaler_std"] = scaler.std_
    return arrays


def load_all(path: pathlib.Path) -> dict:
    with np.load(path, allow_pickle=True) as z:
        return {k: z[k] for k in z.files}


def verify_fold(fold: int, out_root: str | None, K_of: dict | None = None) -> list[str]:
    """Check the capped fold against its source fold (read-only).

    Three invariants must hold for the design to be what it claims:
    each arm's train split has exactly ``K`` windows; val/test are byte-identical
    to the pilot fold; and every retained window is an exact copy of a source
    training window.
    """
    src = REPO / f"artifacts/data_fold{fold}"
    dst = REPO / (out_root or f"artifacts/data_vm_fold{fold}")
    lines = []
    for p in sorted(dst.glob("*.npz")):
        stem = p.stem
        tgt = (stem.replace("single_cond", "") if stem.startswith("single_cond")
               else stem.split("_to_")[1])
        zs = load_all(src / f"{stem}.npz")
        zd = load_all(p)
        n_train = len(zd["train/ratio"])
        orig = {r.tobytes() for r in zs["train/X"]}
        kept = sum(1 for r in zd["train/X"] if r.tobytes() in orig)
        val_same = np.array_equal(zs["val/X"], zd["val/X"])
        test_same = np.array_equal(zs["test/X"], zd["test/X"])
        eq_K = (K_of is None) or (n_train == K_of.get((fold, tgt)))
        ok = val_same and test_same and kept == n_train and eq_K
        lines.append(f"{'OK ' if ok else 'BAD'} f{fold} {stem:<18} n_train={n_train:>4} "
                     f"(K={K_of.get((fold, tgt)) if K_of else '?'}) "
                     f"val_same={val_same} test_same={test_same} subset={kept == n_train}")
    return lines



def build_fold(fold: int, out_root: str | None, configs_dir: pathlib.Path,
               models: list[str]) -> list[dict]:
    src_dir = REPO / f"artifacts/data_fold{fold}"
    if not src_dir.is_dir():
        print(f"!! {src_dir} missing -- run scripts/19_make_matched_folds.py --run first")
        return []
    dst_dir = REPO / (out_root or f"artifacts/data_vm_fold{fold}")
    dst_dir.mkdir(parents=True, exist_ok=True)

    # pass 1: read train sizes and group by target
    npz_paths = sorted(src_dir.glob("*.npz"))
    by_target: dict = {}
    for p in npz_paths:
        tgt = _target_of(p.stem)
        if tgt is None:
            continue
        with np.load(p, allow_pickle=True) as z:
            n_train = int(len(z["train/ratio"]))
        by_target.setdefault(tgt, {})[p.stem] = n_train

    # pass 2: K per target, then write the capped copies
    design = []
    for tgt, arms in sorted(by_target.items()):
        K = min(arms.values())
        design.append({"fold": fold, "target": tgt, "K": K,
                       "arms": dict(sorted(arms.items())),
                       "ratio_to_single": {a: v / arms.get(f"single_cond{tgt}", v)
                                           for a, v in arms.items()}})
        for stem, n_train in sorted(arms.items()):
            arrays = load_all(src_dir / f"{stem}.npz")
            arrays = _cap_train(arrays, K)
            np.savez_compressed(dst_dir / f"{stem}.npz", **arrays)
            side = src_dir / f"{stem}.json"
            if side.exists():
                shutil.copy2(side, dst_dir / f"{stem}.json")
        print(f"[vm] fold{fold} target{tgt}: K={K}  " +
              " ".join(f"{a}={v}" for a, v in sorted(arms.items())))

    idx = src_dir / "index.json"
    if idx.exists():
        shutil.copy2(idx, dst_dir / "index.json")

    # config
    configs_dir.mkdir(parents=True, exist_ok=True)
    val = (fold % 5) + 1
    train = [b for b in (1, 2, 3, 4, 5) if b not in (fold, val)]
    cfg_path = configs_dir / f"fold{fold}.yaml"
    cfg_path.write_text(CONFIG_TEMPLATE.format(
        k=fold, v=val, train=train, models=models,
        data_dir=f"artifacts/data_vm_fold{fold}",
        report_dir=f"artifacts/reports/vm_fold{fold}",
    ), encoding="utf-8")
    print(f"[vm] wrote {cfg_path.relative_to(REPO)}")
    return design


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--folds", nargs="+", type=int, default=[1, 2, 3, 4, 5])
    ap.add_argument("--out-root", default=None,
                    help="override output dir (only sensible for a single fold)")
    ap.add_argument("--configs-dir", default="configs/matched_folds_vm")
    ap.add_argument("--models", nargs="+",
                    default=["se_resnet_bigru", "constant_one", "constant_mean", "ridge"])
    ap.add_argument("--json", default="artifacts/reports/volume_matched_design.json")
    ap.add_argument("--md", default="docs/volume_matched_design.md")
    ap.add_argument("--no-verify", action="store_true", help="skip the built-in verification")
    ap.add_argument("--verify-out", default="artifacts/reports/vm_build_verification.txt")
    args = ap.parse_args()

    if args.out_root and len(args.folds) > 1:
        print("!! --out-root only makes sense with a single fold; ignoring it")
        args.out_root = None

    design = []
    for k in args.folds:
        design += build_fold(k, args.out_root, REPO / args.configs_dir, args.models)

    if not design:
        return 2

    # verification: each arm's train split must hold exactly K, val/test untouched,
    # and every retained window must be an exact copy of a source training window
    if not args.no_verify:
        K_of = {(d["fold"], d["target"]): d["K"] for d in design}
        vlines = []
        for k in args.folds:
            vlines += verify_fold(k, args.out_root, K_of)
            vlines.append("")
        vlines = vlines[:-1]
        vout = REPO / args.verify_out
        vout.parent.mkdir(parents=True, exist_ok=True)
        vout.write_text("\n".join(vlines) + "\n", encoding="utf-8")
        n_ok = sum(1 for x in vlines if x.startswith("OK"))
        n_bad = sum(1 for x in vlines if x.startswith("BAD"))
        print(f"\n[vm] verification: {n_ok} OK, {n_bad} BAD -> {vout.relative_to(REPO)}")

    out_json = REPO / args.json
    out_json.parent.mkdir(parents=True, exist_ok=True)
    out_json.write_text(json.dumps(design, ensure_ascii=False, indent=2), encoding="utf-8")

    lines = ["# Volume-matched fold design (Stage 3.2)", "",
             "For every `(fold, target)` unit, **all four arms** (the in-condition arm plus the",
             "three source variants) are capped to the same `K = min(n_train)`, so both sides of",
             "every paired contrast train on exactly `K` windows. `ratio` is the uncapped",
             "cross/single training-volume ratio, i.e. the confound this design removes.", "",
             "| fold | target | K (capped) | arms before capping (n_train) | uncapped ratio vs single |",
             "|---|---|---|---|---|"]
    for d in design:
        arms = " · ".join(f"`{a}`={v}" for a, v in sorted(d["arms"].items()))
        base = d["arms"][f"single_cond{d['target']}"]
        rs = [v / base for v in d["arms"].values()]
        lines.append(f"| {d['fold']} | cond{d['target']} | **{d['K']}** | {arms} | "
                     f"{min(rs):.2f}–{max(rs):.2f}× |")
    lines += ["", "After capping every row's four arms hold exactly `K` windows "
                  "(verified in `artifacts/reports/vm_build_verification.txt`).", ""]
    out_md = REPO / args.md
    out_md.parent.mkdir(parents=True, exist_ok=True)
    out_md.write_text("\n".join(lines) + "\n", encoding="utf-8")

    Ks = [d["K"] for d in design]
    print(f"\n[vm] {len(design)} units, K in [{min(Ks)}, {max(Ks)}]")
    print(f"[vm] wrote {out_json.relative_to(REPO)} and {out_md.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
