"""Generate (and optionally drive) the leave-one-bearing-out matched folds.

Why
---
``configs/cross_matched_linear.yaml`` is a **pilot / sanity check**: it matches the
two protocols on the test population but yields only ONE paired observation per
(model x target condition) and tests only bearing ``_5`` -- which happens to be
the shortest-lived and hardest bearing in every condition (52 / 339 / 114 min).

This script generalises the matched design to a leave-one-bearing-out 5-fold so
that each (model x target condition) yields **five** paired observations:

    fold k   test bearing k of each target condition
             val  bearing  (k mod 5) + 1
             train the remaining three bearings

Both arms use the identical split, so the ONLY thing that changes between
in-condition and cross-condition is *which condition the training data comes
from*, and the test set is byte-identical. The constant floor is therefore also
identical, so ``R_cross = RMSE_cross / RMSE_single`` needs no rescaling.

Usage
-----
    # 1. just write configs/matched_folds/fold{1..5}.yaml
    python scripts/19_make_matched_folds.py

    # 2. actually run prepare -> single -> cross for every fold
    python scripts/19_make_matched_folds.py --run --models se_resnet_bigru

    # 3. run only the cross arm of one fold
    python scripts/19_make_matched_folds.py --run --folds 3 --skip-single

DO NOT run this before the determinism probe on the pilot config has been read:
per disclosure rule A7 the pipeline's run-to-run spread reaches ~31% on a single
task, and a 5-fold design multiplies the compute by five. See
docs/IP5_reframed_falsifiable_verification.md section 2.
"""

from __future__ import annotations

import argparse
import pathlib
import subprocess
import sys
import time

REPO = pathlib.Path(__file__).resolve().parents[1]
BEARINGS = [1, 2, 3, 4, 5]

# A1: the trivial ladder travels with every table; constant_mean is the strongest
# deployable constant, ridge sits between the constants and the deep models.
DEFAULT_MODELS = ["se_resnet_bigru", "pure_bigru", "cnn", "lstm", "gru",
                  "constant_one", "constant_mean", "ridge"]

CONFIG_TEMPLATE = """\
# AUTO-GENERATED by scripts/19_make_matched_folds.py -- do not edit by hand.
# Leave-one-bearing-out fold {k}: test bearing {k} of every target condition,
# val bearing {v}, train bearings {train}.
#
# Matched 1-factor design: the in-condition arm (splits.single) and the
# cross-condition arm (splits.cross) share train/val/test bearing indices, so the
# only difference is which condition the training data comes from.

data:
  label:
    strategy: linear
    healthy_ratio: 0.8        # ignored by the linear strategy; kept for reference

paths:
  data_dir: artifacts/data_fold{k}
  report_dir: artifacts/reports/matched_fold{k}

splits:
  single:
    train: {train}
    val: [{v}]
    test: [{k}]
  cross:
    source_train: {train}
    source_val: [{v}]
    target_test: [{k}]

uda:
  enabled: true

model:
  mmd_feature: flatten

experiments:
  single:
    models: {models}
  cross:
    models: {models}

report:
  headline_metric: rmse
"""


def fold_split(k: int) -> tuple[list[int], int]:
    """Return (train bearings, val bearing) for fold ``k``.

    The validation bearing rotates with the test bearing so that every fold has
    exactly three training bearings, one validation bearing and one test bearing.
    """
    val = (k % 5) + 1
    train = [b for b in BEARINGS if b not in (k, val)]
    return train, val


def write_configs(out_dir: pathlib.Path, folds: list[int], models: list[str]) -> list[pathlib.Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = []
    for k in folds:
        train, val = fold_split(k)
        text = CONFIG_TEMPLATE.format(k=k, v=val, train=train, models=models)
        p = out_dir / f"fold{k}.yaml"
        p.write_text(text, encoding="utf-8")
        paths.append(p)
        print(f"[folds] wrote {p.relative_to(REPO)}  "
              f"test={k} val={val} train={train}")
    return paths


def run(cmd: list[str], label: str) -> bool:
    t0 = time.time()
    proc = subprocess.run(cmd, capture_output=True, text=True, cwd=str(REPO))
    ok = proc.returncode == 0
    print(f"[folds] {label:<28} exit={proc.returncode} wall={time.time() - t0:.1f}s")
    if not ok:
        tail = "\n".join((proc.stderr or proc.stdout or "").strip().splitlines()[-12:])
        print(tail)
    return ok


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out-dir", default="configs/matched_folds")
    ap.add_argument("--folds", nargs="+", type=int, default=BEARINGS)
    ap.add_argument("--models", nargs="+", default=DEFAULT_MODELS)
    ap.add_argument("--run", action="store_true", help="also execute prepare/single/cross")
    ap.add_argument("--skip-prepare", action="store_true")
    ap.add_argument("--skip-single", action="store_true")
    ap.add_argument("--skip-cross", action="store_true")
    args = ap.parse_args()

    out_dir = REPO / args.out_dir
    paths = write_configs(out_dir, args.folds, args.models)

    if not args.run:
        print("\n[folds] configs written; re-run with --run to execute them.")
        return 0

    py = sys.executable
    for p in paths:
        k = int(p.stem.replace("fold", ""))
        rel = str(p.relative_to(REPO))
        base_report = f"artifacts/reports/matched_fold{k}"

        if not args.skip_prepare:
            if not run([py, "scripts/01_prepare_data.py", "--config", rel],
                       f"prepare fold{k}"):
                return 1

        if not args.skip_single:
            if not run([py, "scripts/02_run_single.py", "--config", rel,
                        "--set", f"paths.report_dir={base_report}/single"],
                       f"single fold{k}"):
                return 1

        if not args.skip_cross:
            if not run([py, "scripts/03_run_cross.py", "--config", rel,
                        "--set", f"paths.report_dir={base_report}/cross"],
                       f"cross fold{k}"):
                return 1

    print("\n[folds] all folds done. Aggregate with scripts/18-style re-analysis "
          "once the per-fold results_full.json files exist.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
